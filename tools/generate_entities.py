"""Generate an immutable HTML5 entity lookup table from Python's standard library."""

import html.entities
import pathlib
import sys


def c_bytes(text):
    return '"' + ''.join(f'\\x{byte:02x}' for byte in text.encode('utf-8')) + '"'


lines = ['/* Generated by tools/generate_entities.py; do not edit. */']
for name, value in sorted(html.entities.html5.items()):
    if name.endswith(';'):
        lines.append(f'{{"{name}", {c_bytes(value)}}},')
pathlib.Path(sys.argv[1]).write_text('\n'.join(lines) + '\n')
